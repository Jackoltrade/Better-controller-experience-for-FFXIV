#!/usr/bin/env python3
"""Generate the offline boss lookup from the pinned upstream CSV (no network)."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/enemy-bosses.csv"
TARGET = ROOT / "src/DualSenseLighting/Core/EnemyBossCatalog.cs"


def render():
    with SOURCE.open(encoding="utf-8-sig", newline="") as source:
        pairs = sorted({(int(row["ContentFinderConditionId"]) << 32) | int(row["BNpcNameId"])
                        for row in csv.DictReader(source)})
    if not pairs or any(pair >> 32 == 0 or pair & 0xFFFFFFFF == 0 for pair in pairs):
        raise ValueError("Boss rows must have a duty and NPC name ID")
    rows = ["        " + ", ".join(f"{pair}UL" for pair in pairs[i:i + 6]) + ","
            for i in range(0, len(pairs), 6)]
    return """// SPDX-License-Identifier: GPL-3.0-only
// Generated by tools/generate-enemy-bosses.py; edit data/enemy-bosses.csv instead.
// Boss data: Critical-Impact/LuminaSupplemental, see data/README.md and THIRD-PARTY-NOTICES.txt.
using System;

namespace DualSenseLighting.Core;

public static class EnemyBossCatalog
{
    // Duty + BNpcName, rather than the current target, health, model size or localized text.
    public static bool IsBoss(uint duty, uint name) => duty != 0 && name != 0 &&
        Array.BinarySearch(Keys, ((ulong)duty << 32) | name) >= 0;

    private static readonly ulong[] Keys =
    {
""" + "\n".join(rows) + "\n    };\n}\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated lookup is out of date")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("EnemyBossCatalog.cs is out of date; run tools/generate-enemy-bosses.py")
        print("Enemy boss catalog matches its source CSV")
    else:
        TARGET.write_text(expected)
